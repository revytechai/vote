#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

ALLOW_MISSING_WEB=false

for arg in "$@"; do
  case "$arg" in
    --allow-missing-web)
      ALLOW_MISSING_WEB=true
      ;;
    *)
      echo "Unknown option: $arg" >&2
      exit 1
      ;;
  esac
done

WEB_PRESENT=false
if [ -f "$REPO_ROOT/web/browser/index.html" ]; then
  WEB_PRESENT=true
elif [ "$ALLOW_MISSING_WEB" = false ]; then
  echo "Error: web/browser/index.html is missing. Pass --allow-missing-web to build without the Angular web frontend." >&2
  exit 1
fi

VERSION="$(node -p "require('$REPO_ROOT/api/package.json').version")"
RELEASE_DIR="$REPO_ROOT/release"
mkdir -p "$RELEASE_DIR"
TARBALL="$RELEASE_DIR/revytechai-vote-$VERSION.tar.gz"

echo "==> Building packages/tally"
pnpm -C "$REPO_ROOT/packages/tally" build

echo "==> Building api"
pnpm -C "$REPO_ROOT/api" build

if [ ! -f "$REPO_ROOT/api/dist/main.js" ]; then
  echo "Error: api/dist/main.js was not generated by api build" >&2
  exit 1
fi

INCLUDE_ITEMS=(
  "api/dist"
  "api/prisma"
  "api/package.json"
  "packages/tally/dist"
  "packages/tally/package.json"
)

if [ "$WEB_PRESENT" = true ]; then
  INCLUDE_ITEMS+=("web/browser")
fi

echo "==> Creating release tarball: $TARBALL"
(
  cd "$REPO_ROOT"
  tar -czf "$TARBALL" "${INCLUDE_ITEMS[@]}"
)

echo "==> Verifying tarball contains api/dist/main.js"
if ! tar -tzf "$TARBALL" api/dist/main.js >/dev/null 2>&1; then
  echo "Verification failed: api/dist/main.js not found in tarball" >&2
  exit 1
fi

echo "Release package created: $TARBALL"
