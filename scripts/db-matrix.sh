#!/usr/bin/env bash
set -euo pipefail

# Database portability test runner for revytechai-vote
# Tests schema migration and API test suite against PostgreSQL and MariaDB/MySQL
#
# Credentials
# -----------
# This script never contains a database password. A credential reaches the
# database in one of the following ways, in order of precedence:
#
#   1. A complete URL in the environment: DATABASE_URL, or POSTGRES_URL /
#      MARIADB_URL for the "all" target. CI uses this form because its
#      throwaway service containers use trust / empty-password authentication.
#   2. A complete URL in the credential file.
#   3. A password in the credential file, combined with the default user,
#      host, port and database for the target.
#
# The credential file defaults to <repo root>/.db-matrix.env and is written
# with mode 0600. Run `./scripts/db-matrix.sh init-env` to create one holding
# a password generated by `openssl rand`. The password is only ever handed to
# a child process through the environment, never on a command line, and it is
# masked in the log output.

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCHEMA_FILE="$REPO_ROOT/api/prisma/schema.prisma"
BACKUP_FILE="$SCHEMA_FILE.bak"
CRED_FILE="${DB_MATRIX_ENV_FILE:-$REPO_ROOT/.db-matrix.env}"

# Masks the password of a database URL so that it never reaches the log.
redact_url() {
  printf '%s' "$1" | sed -E 's#^([a-zA-Z0-9+.-]+://[^:/@]+):[^@]*@#\1:***@#'
}

# Reads a key from the credential file. Returns 1 when the file or the key is
# absent. The file is a plain KEY=VALUE list; values may be quoted.
cred_get() {
  local key="$1"
  local line value

  [ -f "$CRED_FILE" ] || return 1
  line="$(grep -E "^[[:space:]]*(export[[:space:]]+)?${key}=" "$CRED_FILE" | tail -n 1)" || return 1
  [ -n "$line" ] || return 1

  value="${line#*=}"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  value="${value%\"}"
  value="${value#\"}"
  value="${value%\'}"
  value="${value#\'}"
  printf '%s' "$value"
}

# Creates the credential file with a password generated by `openssl rand`.
# The file is written with mode 0600 and is never committed.
init_credential_file() {
  if [ -e "$CRED_FILE" ]; then
    echo "Credential file already exists, leaving it untouched: $CRED_FILE"
    return 0
  fi

  local password
  password="$(openssl rand -hex 24)"

  ( umask 077 && printf 'POSTGRES_PASSWORD=%s\nMARIADB_PASSWORD=%s\n' \
    "$password" "$password" >"$CRED_FILE" )
  chmod 600 "$CRED_FILE"

  echo "Created $CRED_FILE with a randomly generated password (mode 0600)."
  echo "Configure the database server with the password stored in that file."
}

# Percent-encodes the characters that would otherwise terminate the
# userinfo part of a URL. The password generated by `openssl rand -hex` is
# already URL-safe; this only matters for a hand-written credential file.
encode_password() {
  local value="$1"
  value="${value//%/%25}"
  value="${value//@/%40}"
  value="${value//:/%3A}"
  value="${value//\//%2F}"
  value="${value//\?/%3F}"
  value="${value//#/%23}"
  value="${value//\[/%5B}"
  value="${value//\]/%5D}"
  value="${value// /%20}"
  printf '%s' "$value"
}

# Builds a connection URL. The password component is left out when the
# password is empty, which is what trust / empty-password servers expect.
build_url() {
  local scheme="$1" user="$2" password="$3" host="$4" port="$5" database="$6" query="$7"

  local authority="$user"
  if [ -n "$password" ]; then
    authority="$user:$(encode_password "$password")"
  fi

  local url="$scheme://$authority@$host:$port/$database"
  if [ -n "$query" ]; then
    url="$url?$query"
  fi

  printf '%s' "$url"
}

# Resolves the connection URL for a target.
#
#   $1 target key: postgres|mariadb
#   $2 default scheme
#   $3 default user
#   $4 default host
#   $5 default port
#   $6 default database
#   $7 default query string
#   $8 yes when DATABASE_URL may be used for this target
resolve_url() {
  local target="$1" scheme="$2" user="$3" host="$4" port="$5" database="$6" query="$7"
  local use_database_url="$8"

  local url_var="${target^^}_URL"
  local password_var="${target^^}_PASSWORD"

  if [ "$use_database_url" = "yes" ] && [ -n "${DATABASE_URL:-}" ]; then
    printf '%s' "$DATABASE_URL"
    return 0
  fi

  local url="${!url_var:-}"
  if [ -n "$url" ]; then
    printf '%s' "$url"
    return 0
  fi

  url="$(cred_get "$url_var" || true)"
  if [ -n "$url" ]; then
    printf '%s' "$url"
    return 0
  fi

  local password
  password="$(cred_get "$password_var" || true)"

  build_url "$scheme" "$user" "$password" "$host" "$port" "$database" "$query"
}

# Reports whether a target has an explicitly configured URL or password.
target_configured() {
  local target="$1"
  local url_var="${target^^}_URL"
  local password_var="${target^^}_PASSWORD"

  if [ -n "${!url_var:-}" ]; then
    return 0
  fi
  if [ -n "$(cred_get "$url_var" || true)" ]; then
    return 0
  fi
  if [ -n "$(cred_get "$password_var" || true)" ]; then
    return 0
  fi
  return 1
}

# Prints the provider named by the given block (datasource or generator) in
# schema.prisma.
schema_block_provider() {
  awk -v block="$1" '
    $0 ~ "^[[:space:]]*" block "[[:space:]]" { inside = 1 }
    inside && /provider[[:space:]]*=/ {
      if (match($0, /"[^"]+"/)) { print substr($0, RSTART + 1, RLENGTH - 2); exit }
    }
    inside && /^[[:space:]]*}/ { inside = 0 }
  ' "$SCHEMA_FILE"
}

# Rewrites the datasource provider in schema.prisma.
#
# The generator block has a provider of its own and must not be touched:
# rewriting it makes `prisma generate` fail with
# "Generator <provider> failed", because there is no such generator.
swap_datasource_provider() {
  local provider="$1"

  sed -i -E "/^[[:space:]]*datasource[[:space:]]/ , /^[[:space:]]*}/ \
    s/provider[[:space:]]*=[[:space:]]*\"[^\"]+\"/provider = \"$provider\"/" "$SCHEMA_FILE"

  local datasource_provider generator_provider
  datasource_provider="$(schema_block_provider datasource)"
  generator_provider="$(schema_block_provider generator)"

  if [ "$datasource_provider" != "$provider" ]; then
    echo "Failed to set the datasource provider to '$provider' (got '$datasource_provider')." >&2
    return 1
  fi
  if [ "$generator_provider" != "prisma-client-js" ]; then
    echo "The generator provider was changed to '$generator_provider'; it must stay 'prisma-client-js'." >&2
    return 1
  fi
}

cleanup() {
  if [ -f "$BACKUP_FILE" ]; then
    echo "Restoring original schema.prisma..."
    mv -f "$BACKUP_FILE" "$SCHEMA_FILE"
    (cd "$REPO_ROOT/api" && npx prisma generate >/dev/null 2>&1 || true)
  fi
}

run_target() {
  local target="$1"
  local provider="$2"
  local url="$3"

  echo "=========================================="
  echo "Testing target: $target (provider: $provider)"
  echo "URL: $(redact_url "$url")"
  echo "=========================================="

  # Swap provider in schema.prisma
  swap_datasource_provider "$provider"

  cd "$REPO_ROOT/api"

  echo "==> Generating Prisma Client for $provider..."
  DATABASE_URL="$url" npx prisma generate

  echo "==> Pushing schema to $target database..."
  DATABASE_URL="$url" npx prisma db push --skip-generate --accept-data-loss

  echo "==> Running API test suite against $target..."
  DATABASE_URL="$url" pnpm test

  echo "==> Target $target PASSED!"
}

TARGET="${1:-all}"

usage() {
  echo "Usage: $0 [postgres|mariadb|all|init-env]"
}

# Credential bootstrapping touches neither the schema nor the database, so it
# runs before the schema backup is taken.
if [ "$TARGET" = "init-env" ]; then
  init_credential_file
  exit 0
fi

case "$TARGET" in
  postgres|postgresql|mariadb|mysql|all) ;;
  *)
    usage
    exit 1
    ;;
esac

cp "$SCHEMA_FILE" "$BACKUP_FILE"
trap cleanup EXIT

case "$TARGET" in
  postgres|postgresql)
    run_target "PostgreSQL" "postgresql" \
      "$(resolve_url postgres "postgresql" "revy" "localhost" "5432" "revyvote" "schema=public" yes)"
    ;;
  mariadb|mysql)
    run_target "MariaDB" "mysql" \
      "$(resolve_url mariadb "mysql" "root" "localhost" "3306" "revyvote" "" yes)"
    ;;
  all)
    echo "Running all database matrix targets..."
    if target_configured postgres; then
      run_target "PostgreSQL" "postgresql" \
        "$(resolve_url postgres "postgresql" "revy" "localhost" "5432" "revyvote" "schema=public" no)"
    else
      echo "==> Skipping PostgreSQL: set POSTGRES_URL or POSTGRES_PASSWORD to enable it."
    fi
    if target_configured mariadb; then
      run_target "MariaDB" "mysql" \
        "$(resolve_url mariadb "mysql" "root" "localhost" "3306" "revyvote" "" no)"
    else
      echo "==> Skipping MariaDB: set MARIADB_URL or MARIADB_PASSWORD to enable it."
    fi
    ;;
  *)
    usage
    exit 1
    ;;
esac

echo "Database matrix tests completed successfully."
